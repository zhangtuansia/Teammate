// Generates src/lib/emoji-data.ts from emojibase.
//
// The data is generated and committed rather than imported at runtime: this is
// a local-first desktop app, so a picker that fetches its emoji from a CDN
// (which is how most of them work) would be an empty grid on a plane. Keeping
// emojibase as a devDependency also means none of its 6 MB of locales reaches
// the bundle — only the ~1900 emoji we actually show.
//
// Run with: pnpm --filter @teammate/web build:emoji

import { writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const require = createRequire(import.meta.url);
const here = dirname(fileURLToPath(import.meta.url));

const english = require("emojibase-data/en/compact.json");
const chinese = require("emojibase-data/zh/compact.json");
const shortcodes = require("emojibase-data/en/shortcodes/github.json");

// Group 2 is the skin-tone and hair-colour modifiers, which are not emoji you
// can send on their own; entries with no group at all are the regional
// indicator letters that flags are assembled from.
const COMPONENT_GROUP = 2;

const GROUP_KEYS = [
  "smileys",
  "people",
  null,
  "nature",
  "food",
  "travel",
  "activities",
  "objects",
  "symbols",
  "flags",
];

const zhByHexcode = new Map(chinese.map((entry) => [entry.hexcode, entry]));

/** Everything someone might type to find this emoji, in either language. */
function searchTerms(entry) {
  const zh = zhByHexcode.get(entry.hexcode);
  const shortcode = shortcodes[entry.hexcode];
  const terms = [
    entry.label,
    ...(entry.tags ?? []),
    ...(Array.isArray(shortcode) ? shortcode : shortcode ? [shortcode] : []),
    zh?.label,
    ...(zh?.tags ?? []),
  ];
  const seen = new Set();
  for (const term of terms) {
    if (typeof term !== "string") continue;
    const cleaned = term.toLowerCase().trim();
    if (cleaned) seen.add(cleaned);
  }
  return [...seen].join(" ");
}

const rows = english
  .filter((entry) => entry.group !== undefined && entry.group !== COMPONENT_GROUP)
  .sort((a, b) => (a.order ?? 0) - (b.order ?? 0))
  .map((entry) => [entry.unicode, entry.group, entry.label, searchTerms(entry)]);

const body = rows
  .map((row) => `  ${JSON.stringify(row)},`)
  .join("\n");

const file = `// Generated by scripts/build-emoji-data.mjs — do not edit by hand.
// Source: emojibase ${require("emojibase-data/package.json").version}

/** \`[character, group index, English name, search terms]\`. */
export type EmojiEntry = readonly [string, number, string, string];

/** Indexes match the group field of an entry; \`null\` is the modifier group. */
export const EMOJI_GROUP_KEYS = ${JSON.stringify(GROUP_KEYS)} as const;

export const EMOJI: readonly EmojiEntry[] = [
${body}
];
`;

writeFileSync(join(here, "../src/lib/emoji-data.ts"), file);
console.log(`emoji-data.ts: ${rows.length} emoji`);
